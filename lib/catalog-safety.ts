const reviewedSectionIds = new Set<string>(REVIEWED_SECTION_IDS);
const reviewedPresetIds = new Set<string>(REVIEWED_PRESET_IDS);

export function isReviewedPresetId(id: string | null | undefined) {
  return Boolean(id && reviewedPresetIds.has(id));
}

export function isRestrictedPresetId(id: string | null | undefined) {
  return !isReviewedPresetId(id);
}

export function filterSafeTemplates(templates: Template[]) {
  return templates.filter((template) => isReviewedPresetId(template.id));
}

function makeFeaturedBanner(template: Template): FeaturedBanner {
  return {
    id: `featured-${template.id}`,
    title: template.title,
    subtitle: template.subtitle ?? template.description,
    imageUrl: template.coverUrl,
    ctaLabel: "Try",
    presetId: template.id,
    isPro: template.isPro,
  };
}

export function filterSafeCatalog(payload: BootstrapPayload): BootstrapPayload {
  const filterSections = <T extends { id: string; items: Template[] }>(
    sections: T[]
  ): T[] =>
    sections
      .filter((section) => reviewedSectionIds.has(section.id))
      .map((section) => ({
        ...section,
        items: filterSafeTemplates(section.items),
      }))
      .filter((section) => section.items.length > 0);

  const imageSections = filterSections(payload.imageSections);
  const videoSections = filterSections(payload.videoSections);
  let featuredBanner = { ...payload.featuredBanner };

  if (isRestrictedPresetId(featuredBanner.presetId)) {
    const candidates = [...imageSections, ...videoSections].flatMap(
      (section) => section.items
    );
    const fallback =
      candidates.find((item) => item.id === "headshot-pro") ??
      candidates.find((item) => item.id === "pack-product-adshot") ??
      candidates.find((item) => item.id === "content-lab") ??
      candidates[0];

    if (!fallback) {
      throw new Error("Catalog has no reviewed preset for the featured banner.");
    }

    featuredBanner = makeFeaturedBanner(fallback);
  }

  return {
    ...payload,
    featuredBanner,
    imageSections,
    videoSections,
  };
}
